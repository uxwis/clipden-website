const chineseUrl = "https://wiws.me/";
const englishUrl = `${chineseUrl}en/`;
const chinesePage = new URL("../dist/index.html", import.meta.url);
const englishPage = new URL("../dist/en/index.html", import.meta.url);
const hasHan = /\p{Script=Han}/u;
const escapeHtml = value => value.replaceAll("&", "&amp;").replaceAll('"', "&quot;").replaceAll("<", "&lt;").replaceAll(">", "&gt;");

function translate(value) {
  if (!hasHan.test(value)) return value;
  const text = value.trim();
  const translation = copy.get(text);
  if (translation === undefined) throw new Error(`Missing English copy for: ${text}`);
  return value.replace(text, () => escapeHtml(translation));
}

const html = readFileSync(chinesePage, "utf8").replaceAll("\r\n", "\n");
const output = html
  .replace(/(<script type="application\/ld\+json">)\s*([\s\S]*?)\s*(<\/script>)/, (_, start, json, end) => {
    const data = JSON.parse(json);
    const [site, app] = data["@graph"];
    site["@id"] = `${englishUrl}#website`;
    site.url = englishUrl;
    site.inLanguage = "en";
    app.url = englishUrl;
    app.description = copy.get(app.description);
    if (!app.description) throw new Error("Missing English product metadata.");
    return `${start}\n${JSON.stringify(data, null, 2).replace(/^/gm, "    ")}\n  ${end}`;
  })
  .replace(/>([^<>]+)</gu, (match, value) => hasHan.test(value) ? `>${translate(value)}<` : match)
  .replace(/\b(content|placeholder|aria-label|alt)="([^"]*)"/g, (_, attr, value) => `${attr}="${translate(value)}"`)
  .replace('<html lang="zh-CN">', '<html lang="en">')
  .replace('property="og:locale" content="zh_CN"', 'property="og:locale" content="en_US"')
  .replace(`rel="canonical" href="${chineseUrl}"`, `rel="canonical" href="${englishUrl}"`)
  .replace(`property="og:url" content="${chineseUrl}"`, `property="og:url" content="${englishUrl}"`)
  .replace('<a class="language-switch" href="en/" lang="en" hreflang="en" aria-label="Switch to English">EN</a>',
    '<a class="language-switch" href="../" hreflang="zh-CN" aria-label="Switch to Simplified Chinese">ZH</a>')
  .replace(/\b(href|src|poster)="(assets\/[^"]+|styles\.css|mosaic\.js|app\.js)"/g, '$1="../$2"');

if (process.argv.includes("--check")) {
  if (readFileSync(englishPage, "utf8").replaceAll("\r\n", "\n") !== output) {
    throw new Error("The English page is out of date. Run npm run build:en.");
  }
} else {
  mkdirSync(new URL(".", englishPage), { recursive: true });
  writeFileSync(englishPage, output);
}
